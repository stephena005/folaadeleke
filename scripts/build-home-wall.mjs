#!/usr/bin/env node
// Builds the home page wall — the drifting columns of every print — from
// the gallery wall in prints/index.html, which stays the single source of
// truth for titles, sizes, prices, shop links and the New flags.
//
//   node scripts/build-home-wall.mjs            # rewrite index.html's wall + export missing thumbs
//   node scripts/build-home-wall.mjs --check    # exit 1 if index.html's wall is out of date
//
// The cards are static HTML between the WALL:START / WALL:END markers in
// index.html, so search engines and no-JS visitors get every print as a
// real link with alt text. The page script reads them, shuffles them into
// columns and sets them moving. Order here: the three New works first
// (newest first), then the rest of the catalogue newest first.
//
// Each card shows a thumbnail from images/prints/thumbs/<slug>.jpg (640px,
// scripts/export-print-thumb.py), exported from the web JPEG when missing.
//
// scripts/hang-print.mjs calls this after it hangs a print, and
// scripts/check-site.mjs runs the --check comparison on every commit.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, '..');
export const THUMB_DIR = 'images/prints/thumbs';
const START = '<!-- WALL:START';
const END = '<!-- WALL:END -->';

// Every .hang block on the gallery wall, in catalogue terms.
export function readPrints(printsHtml) {
  const out = [];
  const re = /<a class="hang[^"]*" href="#[^"]+" id="([^"]+)"([^>]*)>[\s\S]*?<img src="([^"]+)"/g;
  let m;
  while ((m = re.exec(printsHtml))) {
    const d = Object.fromEntries([...m[2].matchAll(/data-([a-z]+)="([^"]*)"/g)].map((x) => [x[1], x[2]]));
    const web = m[3].replace(/^\//, '');
    out.push({
      slug: m[1], n: Number(d.n), title: d.title, edition: d.edition || 'Edition of 15',
      sizes: d.sizes || '', shop: d.shop || '', isNew: d.new === '1',
      web, thumb: `${THUMB_DIR}/${web.split('/').pop()}`,
    });
  }
  return out;
}

// dims(thumbPath) → { w, h } or null; check-site passes null to compare without them.
export function renderWall(printsHtml, dims) {
  const prints = readPrints(printsHtml);
  const ordered = [
    ...prints.filter((p) => p.isNew).sort((a, b) => b.n - a.n),
    ...prints.filter((p) => !p.isNew).sort((a, b) => b.n - a.n),
  ];
  const cards = ordered.map((p, i) => {
    const sold = !p.shop;
    const d = dims ? dims(p.thumb) : null;
    const size = d ? ` width="${d.w}" height="${d.h}"` : '';
    // the first screenful loads with the page; the rest as they drift into view
    const loading = i < 12 ? 'eager' : 'lazy';
    return [
      `      <a class="card" href="/prints#${p.slug}" data-slug="${p.slug}" data-title="${p.title}" data-edition="${p.edition}" data-sizes="${p.sizes}"` +
        (sold ? ' data-sold="1"' : ` data-shop="${p.shop}"`) + (p.isNew ? ' data-new="1"' : '') + '>',
      (p.isNew ? '        <span class="flag">New</span>\n' : sold ? '        <span class="flag sold">Sold out</span>\n' : '') +
      `        <img src="/${p.thumb}"${size} alt="${p.title} — fine art print by Fola Adeleke" loading="${loading}" decoding="async" />`,
      `        <span class="cap"><span class="t">${p.title}</span>${sold ? '<span class="p">Sold out</span>' : ''}</span>`,
      '      </a>',
    ].join('\n');
  });
  return `${START} — generated by scripts/build-home-wall.mjs from prints/index.html; edit the prints page, not this -->\n${cards.join('\n')}\n      ${END}`;
}

export function replaceWall(homeHtml, block) {
  const a = homeHtml.indexOf(START), b = homeHtml.indexOf(END);
  if (a === -1 || b === -1) throw new Error('index.html has no WALL:START / WALL:END markers');
  return homeHtml.slice(0, a) + block + homeHtml.slice(b + END.length);
}

export function currentWall(homeHtml) {
  const a = homeHtml.indexOf(START), b = homeHtml.indexOf(END);
  return a === -1 || b === -1 ? null : homeHtml.slice(a, b + END.length);
}

// Width and height from a JPEG's SOF marker — no image library needed.
export function jpegSize(buf) {
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    const len = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
      return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
    }
    i += 2 + len;
  }
  return null;
}

export function exportThumb(p, root = repoRoot) {
  const out = execFileSync('python3', [resolve(scriptDir, 'export-print-thumb.py'), resolve(root, p.web), resolve(root, p.thumb)], { encoding: 'utf8' });
  return out.trim();
}

// ── CLI ──────────────────────────────────────────────────────────────────
if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check');
  const printsHtml = readFileSync(resolve(repoRoot, 'prints/index.html'), 'utf8');
  const homePath = resolve(repoRoot, 'index.html');
  const home = readFileSync(homePath, 'utf8');
  const made = [];
  if (!check) {
    for (const p of readPrints(printsHtml)) {
      if (existsSync(resolve(repoRoot, p.thumb))) continue;
      if (!existsSync(resolve(repoRoot, p.web))) { console.error(`build-home-wall: ${p.web} is missing, cannot make ${p.thumb}`); process.exit(1); }
      console.log(`thumb   ${p.thumb} (${exportThumb(p)})`);
      made.push(p.thumb);
    }
  }
  const dims = (path) => (existsSync(resolve(repoRoot, path)) ? jpegSize(readFileSync(resolve(repoRoot, path))) : null);
  const block = renderWall(printsHtml, dims);
  if (check) {
    const strip = (s) => s.replace(/ width="\d+" height="\d+"/g, '');
    const now = currentWall(home);
    if (!now || strip(now) !== strip(block)) { console.error('build-home-wall: index.html wall is out of date — run: node scripts/build-home-wall.mjs'); process.exit(1); }
    console.log('build-home-wall: index.html wall matches prints/index.html');
  } else {
    const next = replaceWall(home, block);
    if (next === home) console.log('build-home-wall: index.html wall already up to date');
    else { writeFileSync(homePath, next); console.log(`build-home-wall: wrote ${readPrints(printsHtml).length} prints to index.html`); }
    if (made.length) console.log(`new thumbs to commit: ${made.join(' ')}`);
  }
}
